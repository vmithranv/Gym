// Helper to extract YouTube video ID from various link formats
export const extractYoutubeId = (urlOrId) => {
  if (!urlOrId) return '';
  const clean = urlOrId.trim();
  if (/^[a-zA-Z0-9_-]{11}$/.test(clean)) {
    return clean;
  }
  const match = clean.match(
    /(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=))([\w-]{11})/
  );
  return match ? match[1] : '';
};

// Helper to infer muscle group from exercise name if not explicitly set
export const getExerciseMuscleGroup = (name) => {
  const guide = EXERCISE_GUIDES[name];
  if (guide?.muscleGroup) return guide.muscleGroup;

  const lower = (name || '').toLowerCase();
  if (lower.includes('bench') || lower.includes('chest') || lower.includes('pec') || lower.includes('dip') || lower.includes('fly')) {
    return 'Chest';
  }
  if (lower.includes('row') || lower.includes('deadlift') || lower.includes('lat') || lower.includes('pullup') || lower.includes('pull-up') || lower.includes('back')) {
    return 'Back';
  }
  if (lower.includes('press') && (lower.includes('overhead') || lower.includes('shoulder') || lower.includes('ohp')) || lower.includes('lateral') || lower.includes('delt')) {
    return 'Shoulders';
  }
  if (lower.includes('curl') || lower.includes('tricep') || lower.includes('bicep') || lower.includes('pushdown') || lower.includes('arm')) {
    return 'Arms';
  }
  if (lower.includes('squat') || lower.includes('leg') || lower.includes('lunge') || lower.includes('calf') || lower.includes('calves') || lower.includes('hamstring') || lower.includes('quad')) {
    return 'Legs';
  }
  return 'Other';
};
