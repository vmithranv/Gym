// Helper to extract YouTube video ID from various link formats (watch, youtu.be, shorts, embed, live)
export const extractYoutubeId = (urlOrId) => {
  if (!urlOrId) return '';
  const clean = urlOrId.trim();
  if (/^[a-zA-Z0-9_-]{11}$/.test(clean)) {
    return clean;
  }
  const match = clean.match(
    /(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|shorts\/|live\/|watch\?v=|watch\?.+&v=))([\w-]{11})/
  );
  return match ? match[1] : '';
};

/**
 * Resolves the canonical YouTube tutorial ID & watch URL for an exercise object or name.
 */
export const getExerciseYoutubeInfo = (exerciseOrName) => {
  const isObj = exerciseOrName && typeof exerciseOrName === 'object';
  const name = isObj ? exerciseOrName.name : String(exerciseOrName || '');
  const customOrExplicit = isObj
    ? exerciseOrName.customVideoUrl || exerciseOrName.youtubeUrl || exerciseOrName.youtubeId || ''
    : '';
  const customId = extractYoutubeId(customOrExplicit);
  const guideId = EXERCISE_GUIDES[name]?.youtubeId || '';
  const youtubeId = customId || guideId;

  return {
    youtubeId,
    url: youtubeId ? `https://www.youtube.com/watch?v=${youtubeId}` : ''
  };
};

export const getExerciseMuscleGroup = (name) => {
  const guide = EXERCISE_GUIDES[name];
  if (guide?.muscleGroup) return guide.muscleGroup;

  const lower = (name || '').toLowerCase();
  if (lower.includes('bench') || lower.includes('chest') || lower.includes('pec') || lower.includes('dip') || lower.includes('fly')) {
    return 'Chest';
  }
  if (lower.includes('row') || lower.includes('deadlift') || lower.includes('lat') || lower.includes('pullup') || lower.includes('pull-up') || lower.includes('back')) {
    return 'Back';
  }
  if (lower.includes('press') && (lower.includes('overhead') || lower.includes('shoulder') || lower.includes('ohp')) || lower.includes('lateral') || lower.includes('delt')) {
    return 'Shoulders';
  }
  if (lower.includes('curl') || lower.includes('tricep') || lower.includes('bicep') || lower.includes('pushdown') || lower.includes('arm')) {
    return 'Arms';
  }
  if (lower.includes('squat') || lower.includes('leg') || lower.includes('lunge') || lower.includes('calf') || lower.includes('calves') || lower.includes('hamstring') || lower.includes('quad')) {
    return 'Legs';
  }
  return 'Other';
};

// Returns recommended rest seconds based on exercise type (105-120s compound, 75s isolation, 120-150s leg compound)
export const getExerciseRecommendedRest = (exerciseName) => {
  const name = (exerciseName || '').toLowerCase();
  if (name.includes('leg press') || name.includes('squat')) {
    return 120; // 2 minutes for heavy leg compounds
  }
  if (name.includes('bench') || name.includes('overhead') || name.includes('press') || name.includes('row') || name.includes('lat pulldown')) {
    return 105; // ~105s (90-120s range) for upper compounds
  }
  return 75; // 75s (60-90s range) for isolation (lateral raises, triceps pushdown, curls, calf raises)
};
